from dataclasses import dataclass, field, asdict
from typing import List, Dict, Optional, Any


@dataclass
class Holding:
    """Represents a single stock position in the user's portfolio."""
    ticker: str
    shares: float
    avg_cost: float
    peak_price: Optional[float] = None  # If None, defaults to 14-day rolling high from yfinance


@dataclass
class StopLossResult:
    """Output of Equation 1: News-Reactive Dynamic Stop-Loss."""
    ticker: str
    current_price: float
    peak_price: float
    atr_14: float
    k_multiplier: float
    sentiment_score: float          # S_news = P_+ - P_- in [-1, 1]
    news_multiplier: float          # M_news = max(m_min, 1 + S_news)
    stop_loss_price: float          # P_stop = P_peak - (k * ATR_14 * M_news)
    distance_to_stop_pct: float     # (current_price - stop_loss_price) / current_price
    triggered: bool                 # True if current_price <= stop_loss_price
    recommended_action: str         # "SELL_IMMEDIATELY" or "HOLD"
    latest_headline: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class RebalanceTrade:
    """A single trade recommendation generated by Sleep Soundly Mode."""
    ticker: str
    action: str                     # "SELL" or "BUY"
    shares: int
    estimated_price: float
    dollar_amount: float
    current_beta: float
    reason: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class BetaShieldResult:
    """Output of Equation 2: 'Sleep Soundly' Portfolio Beta Reduction."""
    total_equity: float
    current_portfolio_beta: float
    target_beta: float
    projected_new_beta: float
    safe_haven_ticker: str
    safe_haven_beta: float
    asset_betas: Dict[str, float]
    current_weights: Dict[str, float]
    new_weights: Dict[str, float]
    trades: List[RebalanceTrade] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class StockAttribution:
    """Per-stock CAPM return decomposition for Equation 3."""
    ticker: str
    weight: float
    beta: float
    stock_return_pct: float         # r_i (in %)
    macro_component_pct: float      # beta_i * r_m (in %)
    idiosyncratic_alpha_pct: float  # alpha_i = r_i - beta_i * r_m (in %)
    portfolio_contribution_pct: float  # w_i * r_i (in %)
    latest_headline: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class AttributionResult:
    """Output of Equation 3: 'Why Is My Portfolio Bleeding?' Return Attribution."""
    total_portfolio_return_pct: float
    total_pnl_dollars: float
    benchmark_ticker: str
    benchmark_return_pct: float
    portfolio_beta: float
    macro_drag_pct: float           # beta_p * r_m (in %)
    idiosyncratic_drag_pct: float   # sum(w_i * alpha_i) (in %)
    macro_share_of_move_pct: float  # % of move explained by macro market
    idiosyncratic_share_pct: float  # % of move explained by stock-specific news
    primary_driver: str             # "MACRO_MARKET" or "STOCK_SPECIFIC"
    stock_breakdown: List[StockAttribution] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class AnomalyResult:
    """Output of Equation 4: Quant Anomaly & Momentum Detection (Z-Score & RSI)."""
    ticker: str
    current_price: float
    intraday_return_pct: float      # r_{i,t} (in %)
    mean_daily_return_pct: float    # \bar{r}_i (in %)
    daily_volatility_pct: float     # \sigma_i (in %)
    z_score: float                  # Z_{i,t} = (r_{i,t} - \bar{r}_i) / \sigma_i
    rsi_14: float                   # 14-day Relative Strength Index (0 to 100)
    rsi_regime: str                 # "OVERSOLD" (<30), "OVERBOUGHT" (>70), or "NEUTRAL"
    wake_llm_agent: bool            # True if |Z| >= z_threshold or RSI extreme
    trigger_reason: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class GuardrailResult:
    """Output of Equation 5: 'Hype-Check' Position Sizing & Value-at-Risk Firewall."""
    ticker: str
    action: str                     # "BUY" or "SELL"
    shares: float
    live_price: float
    trade_notional_dollars: float   # Q_trade * P_i
    total_portfolio_equity: float   # V_total
    concentration_ratio_pct: float  # C_trade = (Q_trade * P_i) / V_total (in %)
    daily_volatility_pct: float     # \sigma_i (in %)
    var_95_dollars: float           # VaR_95 = V_position * 1.645 * \sigma_i
    var_95_pct_of_equity: float     # VaR_95 / V_total (in %)
    status: str                     # "AUTO_EXECUTE" or "REQUIRE_HUMAN_APPROVAL"
    breach_reasons: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
